// Note-specific context menu component
interface NoteContextMenuProps {
  children: React.ReactNode
  noteId: string
  noteTitle: string
  onEdit?: () => void
  onDuplicate?: () => void
  onMove?: () => void
  onDelete?: () => void
  onOpenReadible?: (noteId: string) => void
}

export function NoteContextMenu({
  children,
  noteId,
  noteTitle,
  onEdit,
  onDuplicate,
  onMove,
  onDelete,
  onOpenReadible,
  onPin,
  isPinned
}: NoteContextMenuProps & { onPin?: () => void; isPinned?: boolean }) {
  return (
    <ContextMenu>
      <ContextMenuTrigger asChild>
        {children}
      </ContextMenuTrigger>
      <ContextMenuContent className="w-48">
        <ContextMenuItem onClick={onEdit}>
          <Edit className="mr-2 h-4 w-4" />
          <span>Edit</span>
        </ContextMenuItem>
        <ContextMenuItem onClick={() => {
          if (onOpenReadible) {
            onOpenReadible(noteId)
          }
        }}>
          <Play className="mr-2 h-4 w-4" />
          <span>Open in Readible</span>
        </ContextMenuItem>
        <ContextMenuItem onClick={onDuplicate}>
          <Copy className="mr-2 h-4 w-4" />
          <span>Duplicate</span>
        </ContextMenuItem>
        <ContextMenuItem onClick={onMove}>
          <Move className="mr-2 h-4 w-4" />
          <span>Move to folder</span>
        </ContextMenuItem>
        {onPin && (
          <ContextMenuItem onClick={onPin}>
            <div className="relative mr-2 h-4 w-4">
              <svg
                className={cn("h-4 w-4 transition-transform", isPinned ? "rotate-45" : "")}
                xmlns="http://www.w3.org/2000/svg"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
              >
                <line x1="12" y1="17" x2="12" y2="22"></line>
                <path d="M5 17h14v-1.76a2 2 0 0 0-1.11-1.79l-1.78-.9A2 2 0 0 1 15 10.76V6h1a2 2 0 0 0 0-4H8a2 2 0 0 0 0 4h1v4.76a2 2 0 0 1-1.11 1.79l-1.78.9A2 2 0 0 0 5 15.24Z"></path>
              </svg>
              {isPinned && (
                <div className="absolute -top-1 -right-1 h-2 w-2 rounded-full bg-blue-500" />
              )}
            </div>
            <span>{isPinned ? 'Unpin from Dashboard' : 'Pin to Dashboard'}</span>
          </ContextMenuItem>
        )}
        <ContextMenuSeparator />
        <ContextMenuItem onClick={onDelete} className="text-red-600 dark:text-red-400 focus:text-red-600 dark:focus:text-red-400">
          <Trash2 className="mr-2 h-4 w-4" />
          <span>Delete</span>
        </ContextMenuItem>
      </ContextMenuContent>
    </ContextMenu>
  )
}

